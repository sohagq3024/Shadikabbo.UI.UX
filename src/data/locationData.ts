export function getCitiesForCountry(countryName: string): string[] {
  if (!countryName) return BANGLADESH_DISTRICTS;
  
  // Exact match
  if (POPULAR_CITIES_MAP[countryName]) {
    return POPULAR_CITIES_MAP[countryName];
  }

  // Normalized match (e.g. "USA" vs "United States (USA)")
  const lower = countryName.toLowerCase();
  for (const [key, cities] of Object.entries(POPULAR_CITIES_MAP)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return cities;
    }
  }

  // Default fallback for any other country
  return [
    'Capital / Principal City',
    'Metropolitan Area',
  ];
}
